#!/usr/bin/env node
// Generates the Postgres schema (Supabase migration) from the Base44 entity
// definitions in base44/entities. Run: node scripts/generate-schema.mjs
//
// Conventions (see docs/ARCHITECTURE.md and supabase/README.md):
// - every table keeps Base44's service columns: id, created_date, updated_date,
//   created_by (email), created_by_id (auth user uuid);
// - ids are text so the original Base44 ids survive the migration unchanged;
// - enums are plain text for now (CHECK constraints come after the data import);
// - "required" is not enforced yet: Base44 did not enforce it on old rows either.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entitiesDir = path.join(root, 'base44/entities');
const outFile = path.join(root, 'supabase/migrations/20261122000001_schema.sql');

// Entity name -> table name. User is stored in public.profiles (handwritten below).
export const TABLES = {
  AdConfiguration: 'ad_configurations',
  Article: 'articles',
  Boat: 'boats',
  Bus: 'buses',
  Car: 'cars',
  CarGeneration: 'car_generations',
  CarModelInfo: 'car_model_info',
  Dealer: 'dealers',
  DealerApplication: 'dealer_applications',
  DealerLead: 'dealer_leads',
  DealerPurchaseCriteria: 'dealer_purchase_criteria',
  Favorite: 'favorites',
  ImportRequest: 'import_requests',
  LeadTask: 'lead_tasks',
  ListingPromotion: 'listing_promotions',
  ListingRenewal: 'listing_renewals',
  LuxuryBrand: 'luxury_brands',
  LuxuryCar: 'luxury_cars',
  Message: 'messages',
  MetaAdsOrder: 'meta_ads_orders',
  Motorcycle: 'motorcycles',
  MotorcycleModelInfo: 'motorcycle_model_info',
  Motorhome: 'motorhomes',
  Notification: 'notifications',
  PaymentPurchase: 'payment_purchases',
  PriceOffer: 'price_offers',
  Referral: 'referrals',
  RentalCar: 'rental_cars',
  Report: 'reports',
  Review: 'reviews',
  SaleFeedback: 'sale_feedback',
  SavedSearch: 'saved_searches',
  ServiceRecord: 'service_records',
  SpecialEquipment: 'special_equipment',
  TradeInOffer: 'trade_in_offers',
  Trailer: 'trailers',
  Truck: 'trucks',
  User: 'profiles',
  ViewHistory: 'view_history',
};

const TIMESTAMP_FIELDS = new Set([
  'promotion_until', 'subscription_until', 'bonus_until', 'platform_promotion_until',
  'ad_start_date', 'ad_end_date', 'gdpr_consent_date',
]);
const INTEGER_FIELDS = new Set(['year', 'short_id', 'views_count', 'reviews_count', 'rating_votes', 'sort_order']);

// Columns worth an index, when the table has them.
const INDEX_FIELDS = [
  'status', 'car_id', 'dealer_id', 'listing_id', 'lead_id', 'user_email', 'seller_id', 'seller_email',
  'buyer_email', 'owner_email', 'applicant_email', 'sender_email', 'receiver_email', 'chat_id',
  'author_email', 'dealer_email', 'inviter_email', 'invited_email', 'reporter_email', 'brand', 'country',
];

const stripComments = (s) => s.replace(/^\s*\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function columnType(name, def) {
  if (def.type === 'array') return def.items?.type === 'object' ? 'jsonb' : 'text[]';
  if (def.type === 'object') return 'jsonb';
  if (def.type === 'boolean') return 'boolean';
  if (def.type === 'number' || def.type === 'integer') return INTEGER_FIELDS.has(name) ? 'integer' : 'double precision';
  if (name.endsWith('_at') || TIMESTAMP_FIELDS.has(name)) return 'timestamptz';
  return 'text';
}

function columnComment(def) {
  const parts = [];
  if (def.enum) parts.push(`enum: ${def.enum.join('|')}`);
  if (def.type === 'array' && def.items?.enum) parts.push(`items enum: ${def.items.enum.join('|')}`);
  if (def.description) parts.push(def.description);
  return parts.join(' — ');
}

const SERVICE_COLUMNS = [
  `id text primary key default gen_random_uuid()::text`,
  `created_date timestamptz not null default now()`,
  `updated_date timestamptz not null default now()`,
  `created_by text`,
  `created_by_id uuid references auth.users(id) on delete set null`,
];

const out = [];
out.push(`-- GENERATED by scripts/generate-schema.mjs from base44/entities. Do not edit by hand:`);
out.push(`-- change the generator or add a new migration instead.`);
out.push('');
out.push(`-- Keeps updated_date current on every update.`);
out.push(`create or replace function public.touch_updated_date() returns trigger language plpgsql as $$`);
out.push(`begin new.updated_date := now(); return new; end $$;`);
out.push('');

const files = fs.readdirSync(entitiesDir).filter((f) => f.endsWith('.jsonc')).sort();
const seen = new Set();
for (const file of files) {
  const entity = JSON.parse(stripComments(fs.readFileSync(path.join(entitiesDir, file), 'utf8')));
  const table = TABLES[entity.name];
  if (!table) throw new Error(`No table name for entity ${entity.name}`);
  seen.add(entity.name);
  const props = Object.entries(entity.properties || {});

  let columns;
  if (table === 'profiles') {
    // One row per auth user; id is the auth.users id. legacy_id keeps the Base44 user id.
    columns = [
      `id uuid primary key references auth.users(id) on delete cascade`,
      `legacy_id text unique`,
      `email text not null unique`,
      `full_name text`,
      `role text not null default 'user' check (role in ('user', 'admin'))`,
      `created_date timestamptz not null default now()`,
      `updated_date timestamptz not null default now()`,
    ];
  } else {
    columns = [...SERVICE_COLUMNS];
  }
  const reserved = new Set(columns.map((c) => c.split(' ')[0]));
  const comments = [];
  for (const [name, def] of props) {
    if (reserved.has(name)) continue;
    let col = `${name} ${columnType(name, def)}`;
    if (name === 'short_id') col += ' unique';
    if (def.default !== undefined && ['string', 'number', 'boolean'].includes(typeof def.default)) {
      col += ` default ${typeof def.default === 'string' ? q(def.default) : def.default}`;
    }
    columns.push(col);
    const c = columnComment(def);
    if (c) comments.push(`comment on column public.${table}.${name} is ${q(c)};`);
  }

  out.push(`-- ${entity.name}`);
  out.push(`create table public.${table} (\n  ${columns.join(',\n  ')}\n);`);
  out.push(`comment on table public.${table} is ${q(`Base44 entity ${entity.name}`)};`);
  out.push(...comments);
  out.push(`create trigger ${table}_touch before update on public.${table} for each row execute function public.touch_updated_date();`);
  out.push(`create index ${table}_created_date_idx on public.${table} (created_date desc);`);
  const names = new Set(props.map(([n]) => n));
  for (const f of INDEX_FIELDS) {
    if (names.has(f) && f !== 'short_id') out.push(`create index ${table}_${f}_idx on public.${table} (${f});`);
  }
  out.push('');
}

const missing = Object.keys(TABLES).filter((n) => !seen.has(n));
if (missing.length) throw new Error(`Entities in TABLES without a definition: ${missing.join(', ')}`);

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out.join('\n'));
console.log(`Wrote ${path.relative(root, outFile)}: ${files.length} tables`);
