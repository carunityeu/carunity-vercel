#!/usr/bin/env node
// Converts Base44 CSV exports into one re-runnable SQL file for Supabase.
//
//   node scripts/import-base44.mjs ~/Downloads/Car_export.csv [more.csv ...] [--out migration-data/import.sql] [--check]
//
// - The entity is taken from the file name: "Car_export.csv" -> Car.
// - Values are converted to the column types in supabase/schema-columns.json.
// - Rows are upserted by id, so running the file twice does not duplicate anything.
// - --check loads the result into a local Postgres (PGlite) with all migrations and verifies
//   that every value survived the round trip.
// The output contains personal data (emails, phones): it goes to migration-data/, which is gitignored.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv } from './lib/csv.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(fs.readFileSync(path.join(root, 'supabase/schema-columns.json'), 'utf8'));

const args = process.argv.slice(2);
const check = args.includes('--check');
const outIdx = args.indexOf('--out');
const outFile = path.resolve(outIdx >= 0 ? args[outIdx + 1] : path.join(root, 'migration-data/import.sql'));
const inputs = args.filter((a, i) => !a.startsWith('--') && args[i - 1] !== '--out');
if (!inputs.length) {
  console.error('usage: node scripts/import-base44.mjs <Entity_export.csv>... [--out file.sql] [--check]');
  process.exit(1);
}

// Columns Base44 adds to exports that have no place in our schema.
const IGNORED = new Set(['is_sample']);
// Base44 user ids do not exist in Supabase; links are restored by email after users are imported.
const BASE44_USER_ID_COLUMNS = new Set(['created_by_id']);

const isBase44Id = (v) => /^[0-9a-f]{24}$/.test(v);

function convert(value, type, column, warn) {
  if (value === '' || value === 'null') return null;
  // The export protects values starting with + = - @ with an apostrophe (spreadsheet escaping)
  if (type === 'text' && /^'[+=@-]/.test(value)) value = value.slice(1);
  switch (type) {
    case 'boolean':
      if (value === 'true') return true;
      if (value === 'false') return false;
      warn(`${column}: not a boolean "${value}"`);
      return null;
    case 'integer':
    case 'double':
    case 'double precision': {
      const n = Number(value);
      if (!Number.isFinite(n)) { warn(`${column}: not a number "${value}"`); return null; }
      if (type === 'integer' && !Number.isInteger(n)) { warn(`${column}: rounded ${value}`); return Math.round(n); }
      return n;
    }
    case 'text[]':
    case 'jsonb': {
      try {
        const parsed = JSON.parse(value);
        if (type === 'text[]' && !Array.isArray(parsed)) throw new Error('not an array');
        return type === 'text[]' ? parsed.map((x) => (typeof x === 'string' ? x : JSON.stringify(x))) : parsed;
      } catch (e) {
        if (type === 'text[]') { warn(`${column}: not a JSON array, stored as one item`); return [value]; }
        warn(`${column}: not JSON, stored as a string`);
        return value;
      }
    }
    case 'timestamptz': {
      // Base44 writes service dates without a zone ("2026-11-18T13:17:03.159000"); they are UTC.
      const iso = /[zZ]|[+-]\d\d:?\d\d$/.test(value) ? value : `${value}Z`;
      if (Number.isNaN(Date.parse(iso))) { warn(`${column}: not a date "${value}"`); return null; }
      return iso;
    }
    case 'uuid':
      return null;
    default:
      return value;
  }
}

const sqlLiteral = (s) => `'${s.replace(/'/g, "''")}'`;
const report = [];
const statements = [
  '-- Generated by scripts/import-base44.mjs. Contains personal data: do not commit.',
  'begin;',
];
const loaded = {}; // entity -> { table, rows } for --check

for (const file of inputs) {
  const entity = path.basename(file).replace(/_export.*$/i, '').replace(/\.csv$/i, '');
  const def = schema[entity];
  if (!def) { console.error(`${file}: unknown entity "${entity}"`); process.exit(1); }
  if (def.table === 'profiles') { console.error('User export needs the separate user import (auth accounts); not handled here.'); process.exit(1); }

  const { header, records } = parseCsv(fs.readFileSync(file, 'utf8'));
  const warnings = new Map();
  const warn = (msg) => warnings.set(msg, (warnings.get(msg) || 0) + 1);
  const unknown = header.filter((h) => !(h in def.columns) && !IGNORED.has(h));
  const missing = Object.keys(def.columns).filter((c) => !header.includes(c));

  const rows = records.map((rec) => {
    const row = {};
    for (const [col, type] of Object.entries(def.columns)) {
      if (!(col in rec)) continue;
      if (BASE44_USER_ID_COLUMNS.has(col)) continue;
      row[col] = convert(rec[col], type, col, warn);
    }
    if ('seller_id' in row && row.seller_id && isBase44Id(row.seller_id)) warn('seller_id: Base44 user id instead of an email (fixed after the user import)');
    return row;
  });
  const noId = rows.filter((r) => !r.id).length;
  if (noId) { console.error(`${file}: ${noId} rows without id`); process.exit(1); }

  const cols = Object.keys(def.columns).filter((c) => header.includes(c) && !BASE44_USER_ID_COLUMNS.has(c));
  statements.push(
    `\n-- ${entity}: ${rows.length} rows from ${path.basename(file)}`,
    `insert into public.${def.table} (${cols.join(', ')})`,
    `select ${cols.join(', ')} from jsonb_populate_recordset(null::public.${def.table}, ${sqlLiteral(JSON.stringify(rows))}::jsonb)`,
    `on conflict (id) do update set ${cols.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(', ')};`,
  );
  if ('created_by' in def.columns) {
    statements.push(`update public.${def.table} t set created_by_id = p.id from public.profiles p where t.created_by_id is null and lower(t.created_by) = p.email;`);
  }
  loaded[entity] = { table: def.table, rows };
  report.push({ entity, table: def.table, rows: rows.length, unknown, missing, warnings: [...warnings] });
}
statements.push('\ncommit;');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, statements.join('\n') + '\n');

for (const r of report) {
  console.log(`${r.entity} -> ${r.table}: ${r.rows} rows`);
  if (r.unknown.length) console.log(`  columns not in schema (skipped): ${r.unknown.join(', ')}`);
  if (r.missing.length) console.log(`  schema columns absent in export: ${r.missing.join(', ')}`);
  for (const [w, n] of r.warnings) console.log(`  warning (${n}x): ${w}`);
}
console.log(`SQL written to ${path.relative(process.cwd(), outFile)}`);

if (check) {
  const { PGlite } = await import('@electric-sql/pglite');
  const db = new PGlite();
  await db.exec(fs.readFileSync(path.join(root, 'supabase/tests/supabase-stub.sql'), 'utf8'));
  for (const f of fs.readdirSync(path.join(root, 'supabase/migrations')).sort()) {
    await db.exec(fs.readFileSync(path.join(root, 'supabase/migrations', f), 'utf8'));
  }
  const sql = fs.readFileSync(outFile, 'utf8');
  await db.exec(sql);
  await db.exec(sql); // second run must be a no-op upsert

  const same = (a, b, type) => {
    if (a === null || a === undefined) return b === null || b === undefined;
    if (type === 'timestamptz') return b !== null && Date.parse(a) === new Date(b).getTime();
    return JSON.stringify(a) === JSON.stringify(b);
  };
  let problems = 0;
  for (const [entity, { table, rows }] of Object.entries(loaded)) {
    const types = schema[entity].columns;
    const { rows: dbRows } = await db.query(`select * from public.${table}`);
    const byId = new Map(dbRows.map((r) => [r.id, r]));
    if (dbRows.length !== rows.length) { problems++; console.log(`CHECK ${table}: ${dbRows.length} rows in db, ${rows.length} in export`); }
    for (const row of rows) {
      const got = byId.get(row.id);
      if (!got) { problems++; console.log(`CHECK ${table}: missing ${row.id}`); continue; }
      for (const [col, val] of Object.entries(row)) {
        // short_id is assigned by the database when the export has none.
        if (col === 'short_id' && val === null) continue;
        if (col === 'updated_date') continue; // touched by the second (upsert) run
        if (!same(val, got[col], types[col])) { problems++; console.log(`CHECK ${table}.${col} ${row.id}: ${JSON.stringify(val)} != ${JSON.stringify(got[col])}`); }
      }
    }
    const noShort = 'short_id' in types ? (await db.query(`select count(*)::int as n from public.${table} where short_id is null`)).rows[0].n : 0;
    console.log(`check ${table}: ${dbRows.length} rows round-tripped${noShort ? `, ${noShort} without short_id` : ''}`);
  }
  console.log(problems ? `${problems} problem(s)` : 'check passed: every value matches the export');
  process.exit(problems ? 1 : 0);
}
