#!/usr/bin/env node
// Base44 User export -> Supabase Auth accounts + profiles, as one re-runnable SQL file.
//
//   node scripts/import-users.mjs ~/Downloads/User_export.csv [--out migration-data/05_users.sql] [--check]
//
// What the SQL does (docs/AUTH_MIGRATION.md):
// 1. Creates an auth account per email, confirmed and WITHOUT a password. People sign in with
//    Google (same email) or set a password via "Forgot password?". Existing accounts are kept.
// 2. Adds the e-mail identity Supabase needs to sign such an account in.
// 3. Fills the profile (created by the on_auth_user_created trigger) with the Base44 fields.
// 4. Links every row that has created_by (an email) to the new user id (created_by_id).
// 5. Listings whose seller_id holds a Base44 user id get that user's email instead.
// The output contains personal data: it goes to migration-data/ (gitignored). Run it in the
// Supabase SQL Editor; copy with `LANG=en_US.UTF-8 pbcopy < file` to keep non-Latin text intact.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv } from './lib/csv.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(fs.readFileSync(path.join(root, 'supabase/schema-columns.json'), 'utf8'));
const args = process.argv.slice(2);
const check = args.includes('--check');
const outIdx = args.indexOf('--out');
const outFile = path.resolve(outIdx >= 0 ? args[outIdx + 1] : path.join(root, 'migration-data/05_users.sql'));
const input = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--out');
if (!input) { console.error('usage: node scripts/import-users.mjs <User_export.csv> [--out file.sql] [--check]'); process.exit(1); }

const PROFILE = schema.User.columns;
// Filled by the account itself or the trigger, never copied from the export
const SKIP = new Set(['id', 'email', 'legacy_id', 'created_date', 'updated_date']);
const LISTING_TABLES = ['cars', 'motorcycles', 'trucks', 'buses', 'boats', 'special_equipment', 'trailers', 'motorhomes'];

const toValue = (raw, type) => {
  let v = raw;
  if (v === undefined || v === '' || v === 'null') return null;
  if (type === 'text' && /^'[+=@-]/.test(v)) v = v.slice(1); // spreadsheet escaping in the export
  if (type === 'boolean') return v === 'true' ? true : v === 'false' ? false : null;
  if (type === 'timestamptz') { const iso = /[zZ]|[+-]\d\d:?\d\d$/.test(v) ? v : `${v}Z`; return Number.isNaN(Date.parse(iso)) ? null : iso; }
  return v;
};

const { header, records } = parseCsv(fs.readFileSync(input, 'utf8'));
if (!header.includes('email')) { console.error('No "email" column: is this the User export?'); process.exit(1); }
const seen = new Set();
const users = [];
const problems = [];
for (const r of records) {
  const email = String(r.email || '').trim().toLowerCase();
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) { problems.push(`skipped: invalid email "${r.email}"`); continue; }
  if (seen.has(email)) { problems.push(`skipped: duplicate ${email}`); continue; }
  seen.add(email);
  const profile = {};
  for (const [col, type] of Object.entries(PROFILE)) if (!SKIP.has(col) && col in r) profile[col] = toValue(r[col], type);
  if (profile.role && !['user', 'admin'].includes(profile.role)) { problems.push(`${email}: role "${profile.role}" -> user`); profile.role = 'user'; }
  if (profile.avatar && !/^https?:\/\//.test(profile.avatar)) { problems.push(`${email}: avatar "${profile.avatar}" is not a link -> empty`); profile.avatar = null; }
  if (profile.user_type && !['private', 'dealer'].includes(profile.user_type)) { problems.push(`${email}: user_type "${profile.user_type}" -> private`); profile.user_type = 'private'; }
  if (profile.preferred_language && !['ru', 'en', 'et', 'lv', 'lt'].includes(profile.preferred_language)) profile.preferred_language = null;
  users.push({ legacy_id: r.id || null, email, created_date: toValue(r.created_date, 'timestamptz'), profile });
}
const unknown = header.filter((h) => !(h in PROFILE) && !['id', 'status', 'created_by', 'created_by_id', 'is_sample', 'disabled', 'is_verified', 'app_id', '_app_role'].includes(h));

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;
const json = lit(JSON.stringify(users));
const profileCols = Object.keys(PROFILE).filter((c) => !SKIP.has(c) && header.includes(c));
const recordType = (c) => (PROFILE[c] === 'double' ? 'double precision' : PROFILE[c]);

const sql = `-- Generated by scripts/import-users.mjs from ${path.basename(input)}: ${users.length} users. Contains personal data: do not commit.
begin;

-- 1. Accounts: confirmed, no password (Google sign-in or "Forgot password?" sets one)
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                        raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                        confirmation_token, recovery_token, email_change_token_new, email_change)
select '00000000-0000-0000-0000-000000000000', gen_random_uuid(), 'authenticated', 'authenticated', u.email, '', now(),
       '{"provider":"email","providers":["email"],"imported_from":"base44"}'::jsonb,
       jsonb_strip_nulls(jsonb_build_object('full_name', u.profile ->> 'full_name', 'legacy_id', u.legacy_id)),
       coalesce(u.created_date, now()), now(), '', '', '', ''
from jsonb_to_recordset(${json}::jsonb) as u(legacy_id text, email text, created_date timestamptz, profile jsonb)
where not exists (select 1 from auth.users a where lower(a.email) = u.email);

-- 2. E-mail identity for each imported account
insert into auth.identities (id, user_id, provider_id, identity_data, provider, created_at, updated_at)
select gen_random_uuid(), a.id, a.id::text,
       jsonb_build_object('sub', a.id::text, 'email', a.email, 'email_verified', true), 'email', now(), now()
from auth.users a
where a.raw_app_meta_data ->> 'imported_from' = 'base44'
  and not exists (select 1 from auth.identities i where i.user_id = a.id and i.provider = 'email');

-- 3. Profiles (rows made by the on_auth_user_created trigger): Base44 fields and the old id
update public.profiles p set
  legacy_id = coalesce(p.legacy_id, u.legacy_id)${profileCols.map((c) => `,\n  ${c} = coalesce(x.${c}, p.${c})`).join('')}
from jsonb_to_recordset(${json}::jsonb) as u(legacy_id text, email text, profile jsonb),
     lateral jsonb_to_record(u.profile) as x(${profileCols.map((c) => `${c} ${recordType(c)}`).join(', ') || 'dummy text'})
where p.email = u.email;

-- 4. Link records to their author's new id (every table with created_by + created_by_id)
do $$
declare t text;
begin
  for t in select c.table_name from information_schema.columns c
           where c.table_schema = 'public' and c.column_name = 'created_by'
             and exists (select 1 from information_schema.columns d where d.table_schema = 'public'
                         and d.table_name = c.table_name and d.column_name = 'created_by_id')
  loop
    execute format('update public.%I t set created_by_id = p.id from public.profiles p
                    where t.created_by_id is null and lower(t.created_by) = p.email', t);
  end loop;
end $$;

-- 5. Listings whose seller_id is a Base44 user id instead of an email
${LISTING_TABLES.map((t) => `update public.${t} t set seller_id = p.email from public.profiles p where t.seller_id = p.legacy_id;`).join('\n')}

commit;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, sql);
console.log(`users: ${users.length} (from ${records.length} rows)`);
if (unknown.length) console.log(`columns not copied: ${unknown.join(', ')}`);
for (const p of problems) console.log(`  ${p}`);
console.log(`SQL written to ${path.relative(process.cwd(), outFile)}`);

if (check) {
  // Run against the migrations in a local Postgres with the parts of Supabase's auth schema the SQL touches
  const { PGlite } = await import('@electric-sql/pglite');
  const db = new PGlite();
  await db.exec(fs.readFileSync(path.join(root, 'supabase/tests/supabase-stub.sql'), 'utf8'));
  await db.exec(`alter table auth.users add column instance_id uuid, add column aud text, add column role text,
    add column encrypted_password text, add column email_confirmed_at timestamptz, add column raw_app_meta_data jsonb,
    add column created_at timestamptz, add column updated_at timestamptz, add column confirmation_token text,
    add column recovery_token text, add column email_change_token_new text, add column email_change text;
    create table auth.identities (id uuid primary key, user_id uuid references auth.users(id), provider_id text,
    identity_data jsonb, provider text, created_at timestamptz, updated_at timestamptz);`);
  for (const f of fs.readdirSync(path.join(root, 'supabase/migrations')).sort()) {
    await db.exec(fs.readFileSync(path.join(root, 'supabase/migrations', f), 'utf8'));
  }
  // One listing by the first user, and one whose seller is stored as a Base44 id
  const first = users[0];
  if (first) {
    await db.exec(`insert into public.cars (id, brand, model, status, created_by) values ('chk1', 'Audi', 'A4', 'active', ${lit(first.email)});`);
    if (first.legacy_id) await db.exec(`insert into public.cars (id, brand, model, status, seller_id) values ('chk2', 'Audi', 'A6', 'active', ${lit(first.legacy_id)});`);
  }
  await db.exec(sql);
  await db.exec(sql); // second run must change nothing
  const n = async (q) => (await db.query(q)).rows[0].n;
  const accounts = await n('select count(*)::int n from auth.users');
  const identities = await n('select count(*)::int n from auth.identities');
  const profiles = await n(`select count(*)::int n from public.profiles where email in (${users.map((u) => lit(u.email)).join(',')})`);
  let bad = 0;
  const report = (ok, msg) => { if (!ok) bad++; console.log(`${ok ? 'ok  ' : 'FAIL'} ${msg}`); };
  report(accounts === users.length, `accounts ${accounts}/${users.length} (after two runs)`);
  report(identities === users.length, `identities ${identities}/${users.length}`);
  report(profiles === users.length, `profiles ${profiles}/${users.length}`);
  if (first) {
    report(await n(`select count(*)::int n from public.cars where id = 'chk1' and created_by_id is not null`) === 1, 'listing linked to its author id');
    if (first.legacy_id) report(await n(`select count(*)::int n from public.cars where id = 'chk2' and seller_id = ${lit(first.email)}`) === 1, 'Base44 seller id replaced by email');
    const name = first.profile.full_name;
    if (name) report(await n(`select count(*)::int n from public.profiles where email = ${lit(first.email)} and full_name = ${lit(name)}`) === 1, 'profile fields copied');
  }
  console.log(bad ? `${bad} problem(s)` : 'check passed');
  process.exit(bad ? 1 : 0);
}
