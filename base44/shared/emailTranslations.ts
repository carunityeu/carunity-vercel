/**
 * Get translated email content (subject + strings) for a given email type and language.
 * Falls back to Russian if the language is not available.
 */
export function getEmailStrings(type, lang) {
  const set = emailStrings[type];
  if (!set) return null;
  return set[lang] || set.ru;
}

/**
 * Get translated email subject for a given type, language and context.
 */
export function getEmailSubject(type, lang, ctx) {
  const s = getEmailStrings(type, lang);
  if (!s) return String(ctx?.subject || '');
  return typeof s.subject === 'function' ? s.subject(ctx) : s.subject;
}