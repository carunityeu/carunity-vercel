// Vehicle type -> brand-model map
export const VEHICLE_BRAND_MODELS = {
  bus: busesBrandModels,
  truck: trucksBrandModels,
  trailer: trailersBrandModels,
  boat: boatsBrandModels,
  motorhome: motorhomesBrandModels,
  special: specialEquipmentBrandModels,
};

// Get sorted brand list for a vehicle type
export function getVehicleBrands(vehicleType) {
  const map = VEHICLE_BRAND_MODELS[vehicleType];
  if (!map) return [];
  return Object.keys(map).sort((a, b) => a.localeCompare(b));
}

// Get models for a specific brand in a vehicle type
export function getVehicleModels(vehicleType, brand) {
  const map = VEHICLE_BRAND_MODELS[vehicleType];
  if (!map || !brand) return [];
  return map[brand] || [];
}